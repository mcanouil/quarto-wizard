/**
 * @title Install Record Module
 * @description Reads and writes the Quarto 2 install record.
 *
 * Quarto 2 (`q2 add`) writes `.quarto-source.yml` in each extension folder.
 * The record names the install source and holds a sha256 of each installed file.
 * Before it replaces an extension, a tool compares the files with these hashes
 * so that it does not overwrite local changes.
 *
 * @module filesystem
 */

import * as crypto from "node:crypto";
import * as fs from "node:fs";
import * as path from "node:path";
import * as yaml from "js-yaml";
import * as semver from "semver";
import { ExtensionError } from "../errors.js";
import { formatLocalEdit, type LocalEdit } from "../types/localEdit.js";

/** File name of the install record in an extension folder. */
export const SOURCE_RECORD_FILENAME = ".quarto-source.yml";

/** Schema version of the install record. */
export const SOURCE_RECORD_VERSION = 1;

/** The most folders that the hash walk goes down below the extension folder. */
const MAX_DIRECTORY_DEPTH = 32;

const SOURCE_RECORD_HEADER = [
	"# Generated by Quarto Wizard. Do not edit.",
	"#",
	"# Records where this extension was installed from, and a sha256 of each",
	"# installed file. Before replacing this extension, `q2 add` compares the",
	"# files against these hashes and refuses (without --force) to overwrite",
	"# local changes.",
	"",
].join("\n");

const SOURCE_RECORD_KINDS = ["github", "url", "local-archive", "local-dir"] as const;

/** Type of the install source, as Quarto 2 records it. */
export type SourceRecordKind = (typeof SOURCE_RECORD_KINDS)[number];

/** Contents of an install record. */
export interface SourceRecord {
	/** Schema version. */
	version: number;
	/** The source as typed, with any `@ref`. */
	source: string;
	/** Type of the source. */
	kind: SourceRecordKind;
	/** The text after the last `@` of a GitHub source. */
	ref?: string;
	/** Path relative to the extension folder, to the lowercase hex sha256 of the file. */
	files: Record<string, string>;
	/** Data that only Quarto Wizard uses (YAML key `quarto-wizard`). */
	quartoWizard?: {
		/** YAML key `source-type`. */
		sourceType?: "registry";
		/** Commit of an unpinned install from the default branch. */
		commit?: string;
	};
}

/**
 * Data of an install record, without the file hashes and the schema version.
 */
export type SourceRecordData = Omit<SourceRecord, "files" | "version">;

/** Result of reading an install record. */
export type SourceRecordReadResult =
	{ status: "absent" } | { status: "unreadable" } | { status: "ok"; record: SourceRecord };

/** State of an installed extension, compared with its install record. */
export type InstalledState =
	| { kind: "absent" }
	| { kind: "untracked" }
	| { kind: "unmodified"; record: SourceRecord }
	| { kind: "modified"; edits: LocalEdit[] };

/** What an install does to an extension, as Quarto 2 reports it. */
export type InstallAction = "install" | "update" | "revert" | "no-change";

function compareCodePoints(a: string, b: string): number {
	return Buffer.compare(Buffer.from(a, "utf-8"), Buffer.from(b, "utf-8"));
}

function statFollowingLinks(fullPath: string): fs.Stats {
	try {
		return fs.statSync(fullPath);
	} catch (error) {
		const loop = (error as NodeJS.ErrnoException).code === "ELOOP";
		const reason = loop ? "a symbolic link may point back into its own tree" : (error as Error).message;
		throw new ExtensionError(`Could not read ${fullPath}: ${reason}.`, { cause: error });
	}
}

function hashDirectory(dir: string, relativeDir: string, depth: number, files: Record<string, string>): void {
	for (const name of fs.readdirSync(dir)) {
		const fullPath = path.join(dir, name);
		const relativePath = relativeDir === "" ? name : `${relativeDir}/${name}`;
		if (relativePath === SOURCE_RECORD_FILENAME) {
			continue;
		}
		const stats = statFollowingLinks(fullPath);
		if (stats.isDirectory()) {
			if (depth + 1 > MAX_DIRECTORY_DEPTH) {
				throw new ExtensionError(
					`${fullPath} is more than ${MAX_DIRECTORY_DEPTH} directories deep; a symbolic link may point back into its own tree.`,
				);
			}
			hashDirectory(fullPath, relativePath, depth + 1, files);
		} else if (stats.isFile()) {
			files[relativePath] = crypto.createHash("sha256").update(fs.readFileSync(fullPath)).digest("hex");
		}
	}
}

/**
 * Hash every file in an extension folder, as Quarto 2 does.
 *
 * The walk follows symbolic links and skips the top-level install record.
 * It stops with an error when it goes down more than 32 folders.
 *
 * The result has no prototype, so a file named `__proto__` or `constructor` is an ordinary key.
 * Keys are added in code point order, but JavaScript lists integer-like keys (such as `10`) first.
 * Sort the keys with `compareCodePoints` where the order matters.
 *
 * @param dir - Extension folder
 * @returns Path relative to `dir`, `/`-separated, to the lowercase hex sha256 of the raw bytes
 */
export function hashExtensionFiles(dir: string): Record<string, string> {
	const files: Record<string, string> = Object.create(null);
	hashDirectory(dir, "", 0, files);
	const sorted: Record<string, string> = Object.create(null);
	for (const key of Object.keys(files).sort(compareCodePoints)) {
		sorted[key] = files[key];
	}
	return sorted;
}

function isPlainObject(value: unknown): value is Record<string, unknown> {
	return typeof value === "object" && value !== null && !Array.isArray(value);
}

function isSourceRecordKind(value: unknown): value is SourceRecordKind {
	return (SOURCE_RECORD_KINDS as readonly unknown[]).includes(value);
}

function parseQuartoWizard(value: unknown): SourceRecord["quartoWizard"] {
	if (!isPlainObject(value)) {
		return undefined;
	}
	const data: NonNullable<SourceRecord["quartoWizard"]> = {};
	if (value["source-type"] === "registry") {
		data.sourceType = "registry";
	}
	if (typeof value.commit === "string") {
		data.commit = value.commit;
	}
	return Object.keys(data).length > 0 ? data : undefined;
}

function parseSourceRecord(content: string): SourceRecord | undefined {
	let raw: unknown;
	try {
		raw = yaml.load(content);
	} catch {
		return undefined;
	}
	if (!isPlainObject(raw)) {
		return undefined;
	}
	const { version, source, kind, ref, files } = raw;
	if (!Number.isInteger(version) || typeof source !== "string" || !isSourceRecordKind(kind)) {
		return undefined;
	}
	// A newer schema can give the file hashes another meaning.
	if ((version as number) > SOURCE_RECORD_VERSION) {
		return undefined;
	}
	if (ref !== undefined && ref !== null && typeof ref !== "string") {
		return undefined;
	}
	if (!isPlainObject(files) || !Object.values(files).every((hash) => typeof hash === "string")) {
		return undefined;
	}
	const record: SourceRecord = {
		version: version as number,
		source,
		kind,
		files: files as Record<string, string>,
	};
	if (typeof ref === "string") {
		record.ref = ref;
	}
	const quartoWizard = parseQuartoWizard(raw["quarto-wizard"]);
	if (quartoWizard) {
		record.quartoWizard = quartoWizard;
	}
	return record;
}

/**
 * Read the install record of an extension folder.
 *
 * Leading comments and unknown keys are accepted, as Quarto 2 accepts them.
 * A YAML error, a missing field, a field of the wrong type, an unknown `kind`, or a `version` greater than
 * `SOURCE_RECORD_VERSION` makes the record unreadable.
 *
 * @param dir - Extension folder
 * @returns `absent` when there is no record, `unreadable`, or the record
 */
export function readSourceRecord(dir: string): SourceRecordReadResult {
	const recordPath = path.join(dir, SOURCE_RECORD_FILENAME);
	let content: string;
	try {
		content = fs.readFileSync(recordPath, "utf-8");
	} catch (error) {
		if ((error as NodeJS.ErrnoException).code === "ENOENT") {
			return { status: "absent" };
		}
		return { status: "unreadable" };
	}
	const record = parseSourceRecord(content);
	return record ? { status: "ok", record } : { status: "unreadable" };
}

/**
 * Hash an extension folder and write its install record.
 *
 * The YAML keys are in this order: `version`, `source`, `kind`, `ref`, `files`, `quarto-wizard`.
 * `ref` and `quarto-wizard` are left out when they are empty.
 *
 * @param dir - Extension folder
 * @param record - Source data of the record
 * @returns The record that was written
 */
export function writeSourceRecord(dir: string, record: SourceRecordData): SourceRecord {
	const written: SourceRecord = {
		version: SOURCE_RECORD_VERSION,
		source: record.source,
		kind: record.kind,
		...(record.ref !== undefined && { ref: record.ref }),
		files: hashExtensionFiles(dir),
	};
	const { sourceType, commit } = record.quartoWizard ?? {};
	if (sourceType !== undefined || commit !== undefined) {
		written.quartoWizard = {
			...(sourceType !== undefined && { sourceType }),
			...(commit !== undefined && { commit }),
		};
	}
	fs.writeFileSync(path.join(dir, SOURCE_RECORD_FILENAME), SOURCE_RECORD_HEADER + formatSourceRecord(written), "utf-8");
	return written;
}

function dumpYaml(value: unknown): string {
	return yaml.dump(value, { lineWidth: -1, skipInvalid: true });
}

/**
 * Format a record as YAML.
 *
 * The record has no empty `ref` or `quartoWizard` key, as `writeSourceRecord` builds it.
 * `yaml.dump` leaves out a key whose value is undefined.
 * It would list integer-like keys first, so each `files` entry is dumped
 * on its own, in code point order.
 */
function formatSourceRecord(record: SourceRecord): string {
	const { files: hashes, quartoWizard: wizard, ...fields } = record;
	const head = dumpYaml(fields);
	const paths = Object.keys(hashes).sort(compareCodePoints);
	const files =
		paths.length === 0
			? "files: {}\n"
			: "files:\n" +
				paths
					.map((filePath) => {
						const entry: Record<string, string> = Object.create(null);
						entry[filePath] = hashes[filePath];
						return dumpYaml(entry).replace(/^(?=.)/gm, "  ");
					})
					.join("");
	const quartoWizard = wizard
		? dumpYaml({ "quarto-wizard": { "source-type": wizard.sourceType, commit: wizard.commit } })
		: "";
	return head + files + quartoWizard;
}

/**
 * Compare an installed extension with its install record.
 *
 * An unreadable record counts as a local edit, as Quarto 2 counts it.
 *
 * @param dir - Extension folder
 * @param recordResult - Install record already read from `dir`, read again when not given
 * @returns `absent`, `untracked` (no record), `unmodified`, or `modified` with the edits sorted by path
 */
export function getInstalledState(dir: string, recordResult?: SourceRecordReadResult): InstalledState {
	if (!fs.existsSync(dir)) {
		return { kind: "absent" };
	}
	const result = recordResult ?? readSourceRecord(dir);
	if (result.status === "absent") {
		return { kind: "untracked" };
	}
	if (result.status === "unreadable") {
		return { kind: "modified", edits: [{ path: SOURCE_RECORD_FILENAME, change: "unreadable install record" }] };
	}
	const recorded = result.record.files;
	const current = hashExtensionFiles(dir);
	const edits: LocalEdit[] = [];
	for (const [filePath, hash] of Object.entries(recorded)) {
		if (!Object.hasOwn(current, filePath)) {
			edits.push({ path: filePath, change: "missing" });
		} else if (current[filePath] !== hash) {
			edits.push({ path: filePath, change: "modified" });
		}
	}
	for (const filePath of Object.keys(current)) {
		if (!Object.hasOwn(recorded, filePath)) {
			edits.push({ path: filePath, change: "added" });
		}
	}
	if (edits.length === 0) {
		return { kind: "unmodified", record: result.record };
	}
	return { kind: "modified", edits: edits.sort((a, b) => compareCodePoints(a.path, b.path)) };
}

/**
 * Decide what an install does, with the rules of Quarto 2.
 *
 * Versions are read leniently (`1.2` is `1.2.0`, `v1` is `1.0.0`), and keep their prerelease.
 * A string that is not a version counts as no version.
 * When either side has no version, the install is an update.
 *
 * @param installed - Version of the installed copy, `undefined` when it has no version, or `null` when no copy is installed
 * @param incoming - Version of the copy to install, or `undefined` when it has no version
 * @returns `install`, `update`, `revert`, or `no-change`
 */
export function compareInstallAction(
	installed: string | undefined | null,
	incoming: string | undefined,
): InstallAction {
	if (installed === null) {
		return "install";
	}
	const installedVersion = installed === undefined ? null : semver.coerce(installed, { includePrerelease: true });
	const incomingVersion = incoming === undefined ? null : semver.coerce(incoming, { includePrerelease: true });
	if (!installedVersion || !incomingVersion) {
		return "update";
	}
	const order = semver.compare(incomingVersion, installedVersion);
	if (order > 0) {
		return "update";
	}
	return order < 0 ? "revert" : "no-change";
}

